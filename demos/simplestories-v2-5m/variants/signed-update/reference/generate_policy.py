#!/usr/bin/env python3
"""Regenerate the fixed public DEMO trust-anchor include; no private key input."""
import json
from pathlib import Path
import signed_update as s

root=Path(__file__).resolve().parents[1]
keys=[s.DemoAuthority(i).public_key for i in range(3)]
lines=['// PUBLIC DEMO TRUST ANCHORS. Generated by reference/generate_policy.py.',
       f"localparam [127:0] SU_DOMAIN=128'h{s.DOMAIN.hex()};",
       f"localparam [127:0] SU_ROOT_DOMAIN=128'h{s.ROOT_DOMAIN.hex()};",
       f"localparam [255:0] SU_GEOMETRY=256'h{s.GEOMETRY.hex()};"]
for name,a,b in [('su_authority_identifier',8,24),('su_authority_root',24,56)]:
    width=(b-a)*8
    lines += [f'function automatic [{width-1}:0] {name}(input [1:0] key_id);','  case(key_id)']
    for i,k in enumerate(keys):lines += [f"    2'd{i}: {name}={width}'h{k[a:b].hex()};"]
    lines += [f"    default: {name}={width}'d0;",'  endcase','endfunction']
(root/'rtl/su_policy.svh').write_text('\n'.join(lines)+'\n')
print('Regenerated fixed PUBLIC DEMO policy')
