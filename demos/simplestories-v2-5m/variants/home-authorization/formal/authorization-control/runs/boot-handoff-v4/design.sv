        .start_i(lease_owner ? lease_crypto_start_i : state_q==AUTH_START),
        .public_i_i(lease_owner ? lease_key_id_i : su_authority_identifier(key_q)),
        .public_root_i(lease_owner ? lease_key_root_i : su_authority_root(key_q)),
        .message_length_i(9'd128),.signature_address_o(lms_signature_address),
        .signature_byte_i(lease_owner ? lease_signature_byte_i : signature_read_q),
        .signature_ready_i(lease_owner ? lease_signature_ready_i : signature_ready),.message_address_o(lms_message_address),
        .message_byte_i(lease_owner ? lease_message_byte_i : manifest_q[lms_message_address[6:0]]),
        .busy_o(lms_busy),.done_o(lms_done),.valid_o(lms_valid),.fault_o(lms_fault),
        .shared_hash_start_o(lms_hash_start),.shared_hash_byte_valid_o(lms_hash_byte_valid),
        .shared_hash_length_o(lms_hash_length),.shared_hash_byte_o(lms_hash_byte),
        .shared_hash_ready_i(selected_lms_reset_n && lms_hash_selected && root_ready),
        .shared_hash_busy_i(selected_lms_reset_n && lms_hash_selected && root_busy),
        .shared_hash_done_i(selected_lms_reset_n && lms_hash_selected && root_done),
        .shared_hash_fault_i(selected_lms_reset_n && lms_hash_selected && root_fault),
        .shared_hash_offset_i(lms_hash_selected ? root_offset : 32'd0),
        .shared_hash_digest_i(lms_hash_selected ? root_digest : 256'd0),
        .proof_lease_owner_i(lease_owner),.proof_started_o(proof_verifier_started),
        .proof_lease_epoch_o(proof_verifier_lease_epoch),.proof_identifier_o(proof_verifier_identifier),
        .proof_root_o(proof_verifier_root),.proof_length_o(proof_verifier_length));
    assign boot_ready_o=state_q==LOAD && !fault_q;
    assign sealed_o=state_q==RUN && !fail_closed_o;
    assign fail_closed_o=fault_q || root_fault || (state_q==AUTH_WAIT && lms_fault);
    assign expected_image_sha_o=sealed_o ? image_sha_q : 256'd0;
    assign model_commitment_o=sealed_o ? signed_root_q : 256'd0;
    assign digest_data_o=sealed_o ? digest_read_q : 32'd0;
    assign metadata_data_o=sealed_o ? metadata_read_q : 192'd0;
