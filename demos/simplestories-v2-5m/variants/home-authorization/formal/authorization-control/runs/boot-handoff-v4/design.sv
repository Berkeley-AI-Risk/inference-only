    // the preceding phase finishes: root, model signatures, nonce, home grant.
    wire lms_hash_selected=SHARE_LMS_HASH &&
        (lms_hash_start || (hash_owner_lms_q && !root_hash_start && !nonce_hash_start));
    wire hash_collision=SHARE_LMS_HASH &&
        ((lms_hash_start && (root_hash_start || nonce_hash_start)) ||
         (root_busy && (lms_hash_start || root_hash_start || nonce_hash_start)));
