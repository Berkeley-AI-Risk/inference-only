    wire [127:0] geometry_fields={32'd7265984,32'd1774,32'd55872,32'd0};
    logic manifest_match;
`ifndef SYNTHESIS
    logic input_x_fault;
    always_comb begin
        input_x_fault=$isunknown(boot_valid_i) || $isunknown(digest_read_i) || $isunknown(metadata_read_i);
