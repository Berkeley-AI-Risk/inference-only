    assign nonce_hash_fault_o=nonce_hash_owner && root_fault;
    assign nonce_hash_offset_o=nonce_hash_owner && !lms_hash_selected ? root_offset : 32'd0;
    assign nonce_hash_digest_o=nonce_hash_owner && !lms_hash_selected ? root_digest : 256'd0;

    wire lease_owner=SHARE_VERIFIER && state_q==RUN && !fault_q && !root_fault;
