    wire boot_fire=boot_valid_i && boot_ready_o;
    wire [17:0] payload_offset=received_q-signature_end_q;
    wire [17:0] table_offset=payload_offset-18'd32;
    wire root_done,root_fault,root_busy,root_ready;
    wire [255:0] root_digest;
    wire [31:0] root_offset;
    logic [31:0] root_fetched_offset_q;
    logic root_fetched_q;
    logic [7:0] root_byte;
    logic [13:0] root_digest_address;
    logic [11:0] root_metadata_address;
    wire root_byte_valid=state_q==ROOT_WAIT && root_fetched_q && root_fetched_offset_q==root_offset;
    wire root_byte_fire=root_byte_valid && root_ready;
    wire digest_memory_read=state_q==ROOT_WAIT || (sealed_o && digest_read_i && 32'(digest_address_i)<DIGEST_WORDS);
    wire metadata_memory_read=state_q==ROOT_WAIT || (sealed_o && metadata_read_i && 32'(metadata_address_i)<METADATA_WORDS);
    wire [13:0] digest_memory_address=state_q==ROOT_WAIT ? root_digest_address : digest_address_i;
    wire [11:0] metadata_memory_address=state_q==ROOT_WAIT ? root_metadata_address : metadata_address_i;
    integer a;
    wire lms_reset_n=reset_n && (state_q==AUTH_START || state_q==AUTH_WAIT);
    wire [10:0] lms_signature_address;
    wire [7:0] lms_message_address;
    wire lms_busy,lms_done,lms_valid,lms_fault;
    wire [11:0] signature_index=12'(int'(slot_q)*RECORD_BYTES+4+int'(lms_signature_address));
    wire [11:0] key_index=12'(int'(slot_q)*RECORD_BYTES+int'(id_byte_q));
    wire signature_memory_read=state_q==AUTH_ID || state_q==AUTH_START || state_q==AUTH_WAIT;
    wire [11:0] signature_memory_address=state_q==AUTH_ID ? key_index : signature_index;
    logic [7:0] signature_read_q;
    logic [11:0] signature_read_address_q;
    logic signature_read_valid_q;
