"""Reproduce the source-bound CLEAR epoch proof; recorded-only launches no tools."""
import argparse,concurrent.futures,hashlib,importlib.util,json,os,subprocess,sys,tarfile,time
from pathlib import Path
sys.dont_write_bytecode=True
HERE=Path(__file__).resolve().parent
def sha(b):return hashlib.sha256(b).hexdigest()
def save(path,value):path.write_text(json.dumps(value,indent=2,sort_keys=True)+'\n')
def unpack(out):
 package=json.loads((HERE/'PACKAGE.json').read_text())
 actual={f.name for f in HERE.iterdir()if f.is_file()and f.name!='PACKAGE.json'}
 assert actual==set(package['files']),'Unexpected/missing package file'
 for name,row in package['files'].items():
  f=HERE/name;assert not f.is_symlink()and f.stat().st_size==row['bytes']and sha(f.read_bytes())==row['sha256'],name
 project=out/'project';project.mkdir()
 with tarfile.open(HERE/'project.tar.gz','r:gz')as tar:
  for member in tar.getmembers():
   p=Path(member.name)
   assert not p.is_absolute()and'..'not in p.parts and(member.isdir()or member.isfile()),member.name
   dest=project/p
   if member.isdir():dest.mkdir(parents=True,exist_ok=True)
   else:
    dest.parent.mkdir(parents=True,exist_ok=True);dest.write_bytes(tar.extractfile(member).read())
 return project,package
def logical_smt(raw):
 first,rest=raw.split(b'\n',1)
 assert first.startswith(b'; SMT-LIBv2 description generated by Yosys '),'Unexpected native SMT header'
 return rest
def logical_json(raw):
 value=json.loads(raw);assert 'creator'in value and 'modules'in value
 return{k:v for k,v in value.items()if k!='creator'}
def fresh_models(project,out,source,core,deadline):
 overrides={};records=[]
 for role in ['original','omit-increment','suppress-exhaustion-fault']:
  assert time.monotonic()<deadline-60,'Insufficient total budget for compiler'
  target=out/'fresh-models'/role;target.mkdir(parents=True)
  for name in ['native.sv','compile.ys']:(target/name).write_bytes((project/'models'/role/name).read_bytes())
  command=['yosys','-Q','compile.ys'];start=time.monotonic()
  with(target/'compile.log').open('w')as log:r=subprocess.run(command,cwd=target,stdout=log,stderr=subprocess.STDOUT,timeout=60)
  assert r.returncode==0,('Native compile failed',role)
  old_smt=(project/'models'/role/'native.smt2').read_bytes();fresh_smt=(target/'native.smt2').read_bytes()
  old_json=(project/'models'/role/'native.json').read_bytes();fresh_json=(target/'native.json').read_bytes()
  assert logical_smt(fresh_smt)==logical_smt(old_smt),('Logical SMT identity mismatch',role)
  assert logical_json(fresh_json)==logical_json(old_json),('Circuit JSON identity mismatch',role)
  # Only the first comment line is rebound to the recorded generator banner.
  bound=old_smt.split(b'\n',1)[0]+b'\n'+logical_smt(fresh_smt)
  (target/'bound-native.smt2').write_bytes(bound);assert bound==old_smt
  receipt={'role':role,'command':command,'exit_code':r.returncode,'seconds':time.monotonic()-start,'native_smt_sha256':sha(fresh_smt),'native_json_sha256':sha(fresh_json),'raw_byte_identical':fresh_smt==old_smt and fresh_json==old_json,'logical_smt_byte_identical':True,'circuit_json_equal_except_creator':True,'normalization':'Only first Yosys generator comment and top-level JSON creator metadata; all logical/model content exact','bound_query_model_sha256':sha(bound)}
  save(target/'RESULT.json',receipt);records.append(receipt)
  overrides['models/'+role+'/native.smt2']=target/'bound-native.smt2'
 return overrides,records
def solve(project,out,name,node,args,deadline,core):
 d=out/'fresh-solvers'/name;d.mkdir(parents=True)
 command=([ 'z3','-memory:'+str(args.memory_mb),'-T:'+str(args.timeout),node['query']]if node['solver']=='z3'else['cvc5','--lang=smt2','--tlimit='+str(args.timeout*1000),'--solve-bv-as-int=sum',node['query']])
 started=time.monotonic();peak=0;stop=None;proc=None;code=None
 try:
  assert started<deadline,'Total replay deadline reached before launch'
  with(d/'solver.log').open('w')as log:
   proc=subprocess.Popen(command,cwd=project,stdout=log,stderr=subprocess.STDOUT,start_new_session=True)
   while proc.poll()is None:
    if time.monotonic()-started>args.timeout:stop='per-query-timeout'
    if time.monotonic()>deadline:stop='total-timeout'
    rss=subprocess.run(['ps','-o','rss=','-p',str(proc.pid)],capture_output=True,text=True,check=False)
    if rss.stdout.strip().isdigit():
     current=int(rss.stdout.strip())*1024;peak=max(peak,current)
     if current>args.memory_mb*1024*1024:stop='per-query-RSS-stop'
    if stop:
     proc.kill();break
    time.sleep(0.1)
   code=proc.wait()
 except (OSError,AssertionError)as error:
  stop='launch-or-watchdog-error: '+str(error)
 finally:
  if proc is not None and proc.poll()is None:proc.kill();proc.wait()
 raw=(d/'solver.log').read_bytes()if(d/'solver.log').exists()else b''
 passed=code==0 and stop is None and raw.strip().decode()==node['expected']
 result={'node':name,'engine':node['solver'],'command':command,'expected':node['expected'],'exit_code':code,'stop_reason':stop,'seconds':time.monotonic()-started,'peak_RSS_bytes':peak,'query_sha256':node['query_sha256'],'raw_log_sha256':sha(raw),'expected_result_matched':passed}
 save(d/'RESULT.json',result);print(name+': '+('PASS'if passed else'UNRESOLVED'),flush=True)
 return result
def main():
 ap=argparse.ArgumentParser(description=__doc__);ap.add_argument('--recorded-only',action='store_true');ap.add_argument('--out',type=Path,required=True);ap.add_argument('--model',type=Path,required=True);ap.add_argument('--timeout',type=int,default=120);ap.add_argument('--total-timeout',type=int,default=900);ap.add_argument('--workers',type=int,default=2);ap.add_argument('--memory-mb',type=int,default=4096);args=ap.parse_args()
 assert 0<args.timeout<=600 and 1<=args.workers<=2 and args.memory_mb>=256 and args.total_timeout>0
 out=args.out.resolve();assert not out.exists(),'Use a new output directory';out.mkdir(parents=True)
 started=time.monotonic()
 try:
  project,package=unpack(out)
  spec=importlib.util.spec_from_file_location('clear_epoch_check',project/'check.py');core=importlib.util.module_from_spec(spec);spec.loader.exec_module(core)
  source=json.loads((HERE/'SOURCE.json').read_text())
  result,graph=core.validate(project,source,args.model.resolve(),HERE/'THEOREM.smt2')
  result.update(mode='recorded-only'if args.recorded_only else'fresh',source_files_checked=len(source['production_files']),package_archive_sha256=sha((HERE/'project.tar.gz').read_bytes()),recorded_answers_checked=len(graph['nodes']),fresh_native_compilations=0,fresh_solver_queries=0)
  if not args.recorded_only:
   deadline=started+args.total_timeout
   overrides,compiled=fresh_models(project,out,source,core,deadline)
   for name,node in graph['nodes'].items():assert core.build_query(project,node,overrides)==(project/node['query']).read_bytes(),('Fresh model/query binding mismatch',name)
   with concurrent.futures.ThreadPoolExecutor(max_workers=args.workers)as pool:
    futures=[pool.submit(solve,project,out,n,row,args,deadline,core)for n,row in graph['nodes'].items()]
    replies=[f.result()for f in futures]
   assert all(r['expected_result_matched']for r in replies),'One or more fresh queries unresolved; no fresh qualification'
   result.update(fresh_native_compilations=len(compiled),fresh_solver_queries=len(replies),all_fresh_expected_results_matched=True)
  result.update(passed=True,seconds=time.monotonic()-started)
  save(out/'RESULT.json',result);print(json.dumps(result,indent=2))
 except Exception as error:
  save(out/'FAILURE.json',{'passed':False,'error':str(error),'seconds':time.monotonic()-started});raise
if __name__=='__main__':main()
