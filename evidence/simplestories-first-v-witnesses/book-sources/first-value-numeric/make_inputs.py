#!/usr/bin/env python3
"""Write the model image and the read-only memories as ACL2 books.

usage: python3 -I make_inputs.py PREPARED_DIR OUT_DIR

  PREPARED_DIR  a directory written by the corrected-cycle chain's
                prepare_run_inputs.py: image.lsp, rom.lsp, PREPARED.txt
  OUT_DIR       where ssv-image.lisp and kvn-rom.lisp are written

Nothing here is trusted by a proof for more than this: the two books hold
constants, and the theorems are about those constants.  What ties the
constants to the pinned files is checked here and recorded in INPUTS.txt:

  * the image file has the pinned SHA-256 and 227,062 words of 32 bytes;
  * word w of the constant is the little-endian integer of bytes
    [32w, 32w+32) of that file, computed here from the file itself and
    compared with image.lsp word for word;
  * image.lsp and rom.lsp have the SHA-256 the certified chain's runs
    recorded for the packed files they used.

The book ssv-image-sha256 then has ACL2 itself compute the SHA-256 of the
bytes of the constant.
"""
import hashlib
import os
import re
import sys

IMAGE_SHA = "cad8d015db37a3603e340edfc0009f36d6b12de2bc789d60687011fc700cc3b0"
IMAGE_WORDS = 227062
# the packed files of the runs of the corrected-cycle chain and of held-clear-record
IMAGE_LSP_SHA = "345734f38f86bc6d497b5c3c63c27d7a92aef3f95d7647b4a3c61dd27b09ca53"
ROM_LSP_SHA = "6a4a6379204474068c10192bdf0ca794ec51a3f7ebcf2320cbcaec1cc432cbee"


def fail(msg):
    sys.stderr.write("make_inputs: " + msg + "\n")
    sys.exit(1)


def sha(data):
    return hashlib.sha256(data).hexdigest()


def main():
    if len(sys.argv) != 3:
        fail("usage: make_inputs.py PREPARED_DIR OUT_DIR")
    prepared, out = sys.argv[1:]
    notes = []
    with open(os.path.join(prepared, "PREPARED.txt")) as f:
        first = f.readline().split()
    if len(first) != 2 or first[0] != IMAGE_SHA:
        fail("PREPARED.txt does not start with the pinned image")
    image_path = first[1]
    with open(image_path, "rb") as f:
        image = f.read()
    if sha(image) != IMAGE_SHA:
        fail("the image file does not have the pinned SHA-256")
    if len(image) != 32 * IMAGE_WORDS:
        fail("the image file has %d bytes" % len(image))
    notes.append("%s  %s (%d bytes)" % (IMAGE_SHA, image_path, len(image)))
    words = [int.from_bytes(image[32 * w:32 * w + 32], "little") for w in range(IMAGE_WORDS)]

    with open(os.path.join(prepared, "image.lsp"), "rb") as f:
        image_lsp = f.read()
    if sha(image_lsp) != IMAGE_LSP_SHA:
        fail("image.lsp does not have the SHA-256 the chain's runs recorded")
    text = image_lsp.decode("ascii")
    listed = re.findall(r"^#x([0-9a-f]+)$", text, re.MULTILINE)
    if text != "(\n" + "".join("#x%s\n" % h for h in listed) + ")\n":
        fail("image.lsp is not a list of hexadecimal words, one per line")
    if [int(h, 16) for h in listed] != words:
        fail("image.lsp differs from the words of the image file")
    notes.append("%s  image.lsp of the chain's runs: the same %d words" % (IMAGE_LSP_SHA, len(words)))

    with open(os.path.join(prepared, "rom.lsp"), "rb") as f:
        rom_lsp = f.read()
    if sha(rom_lsp) != ROM_LSP_SHA:
        fail("rom.lsp does not have the SHA-256 the chain's runs recorded")
    rom_text = rom_lsp.decode("ascii")
    entries = re.findall(r'^ (\(\(:var \((?:"[A-Za-z0-9_]+" )+\. "[A-Za-z0-9_]+"\) \. 0\) \. #x[0-9a-f]+\))$',
                         rom_text, re.MULTILINE)
    if rom_text != "(\n" + "".join(" %s\n" % e for e in entries) + ")\n" or len(entries) != 6:
        fail("rom.lsp is not the six bindings expected")
    notes.append("%s  rom.lsp of the chain's runs: %d bindings" % (ROM_LSP_SHA, len(entries)))

    image_book = os.path.join(out, "ssv-image.lisp")
    with open(image_book, "w") as f:
        f.write("; GENERATED by make_inputs.py.  Do not edit.\n"
                "; The SimpleStories model image, SHA-256\n"
                ";   %s,\n"
                "; as %d words of 256 bits: word w is the little-endian integer of\n"
                "; bytes [32w, 32w+32) of the file.\n"
                '(in-package "ACL2")\n'
                "(defconst *ssv-image*\n '(\n" % (IMAGE_SHA, IMAGE_WORDS))
        for w in words:
            f.write("#x%x\n" % w)
        f.write("))\n"
                "; the image, as a function of no arguments\n"
                "(defun ssv-image () (declare (xargs :guard t)) *ssv-image*)\n"
                "(in-theory (disable ssv-image (:e ssv-image)))\n")
    rom_book = os.path.join(out, "kvn-rom.lisp")
    with open(rom_book, "w") as f:
        f.write("; GENERATED by make_inputs.py.  Do not edit.\n"
                "; The contents the pinned RTL loads into its read-only memories, as the\n"
                "; bindings of the six memory variables of the translated design\n"
                "; (see the chain's prepare_run_inputs.py for how each is packed).\n"
                '(in-package "SV")\n'
                "(defconst *kvn-rom*\n '(\n")
        for e in entries:
            f.write(" %s\n" % e)
        f.write("))\n"
                "; the bindings, as a function of no arguments\n"
                "(defun kvn-rom () (declare (xargs :guard t)) *kvn-rom*)\n"
                "(in-theory (disable kvn-rom (:e kvn-rom)))\n")
    for path in (image_book, rom_book):
        with open(path, "rb") as f:
            notes.append("%s  %s (generated)" % (sha(f.read()), os.path.basename(path)))
    with open(os.path.join(out, "INPUTS.txt"), "w") as f:
        f.write("\n".join(notes) + "\n")
    sys.stdout.write("\n".join(notes) + "\n")


if __name__ == "__main__":
    main()
