"""Certify the numerical prerequisites of the first SimpleStories value vector."""
import argparse
import hashlib
import json
import os
from pathlib import Path
import shutil
import subprocess


HERE = Path(__file__).resolve().parent
MODEL = Path("demos/simplestories-v2-5m/assets/board1-real-semantic-image2048.bin")
MODEL_SHA = "cad8d015db37a3603e340edfc0009f36d6b12de2bc789d60687011fc700cc3b0"
IMAGE_BOOK_SHA = "dbe4e66b4405b2ea5664f0602243a60a79f8872f10ec6b3668a3ec1a7aaf9414"
THEOREM = "EVERY-VOCABULARY-TOKEN-MEETS-FIRST-V-NUMERIC-PROFILE"


def sha(path):
    return hashlib.sha256(path.read_bytes()).hexdigest()


def write_image_book(path, image):
    if len(image) != 7_265_984 or hashlib.sha256(image).hexdigest() != MODEL_SHA:
        raise ValueError("The model image differs from the published SimpleStories image.")
    with path.open("x", encoding="ascii", newline="\n") as book:
        book.write(
            "; GENERATED by make_inputs.py.  Do not edit.\n"
            "; The SimpleStories model image, SHA-256\n"
            f";   {MODEL_SHA},\n"
            "; as 227062 words of 256 bits: word w is the little-endian integer of\n"
            "; bytes [32w, 32w+32) of the file.\n"
            '(in-package "ACL2")\n(defconst *ssv-image*\n \'(\n'
        )
        for offset in range(0, len(image), 32):
            word = int.from_bytes(image[offset:offset + 32], "little")
            book.write(f"#x{word:x}\n")
        book.write(
            "))\n; the image, as a function of no arguments\n"
            "(defun ssv-image () (declare (xargs :guard t)) *ssv-image*)\n"
            "(in-theory (disable ssv-image (:e ssv-image)))\n"
        )
    if sha(path) != IMAGE_BOOK_SHA:
        raise ValueError("The generated ACL2 image differs from the one used for certification.")


def run_acl2(binary, env, directory, label, commands):
    log = directory / (label + ".log")
    with log.open("xb") as stream:
        result = subprocess.run([str(binary)], cwd=directory, env=env,
                                input=(commands + "\n(good-bye 0)\n").encode(),
                                stdout=stream, stderr=subprocess.STDOUT)
    output = log.read_text(errors="replace")
    if (result.returncode or "ACL2 Version 8.7 " not in output
            or "ACL2 Error" in output or "******** FAILED ********" in output):
        raise RuntimeError(f"ACL2 did not complete {label}. See {log}")
    return output, {"exit": result.returncode, "log_sha256": sha(log)}


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--acl2", type=Path, required=True, help="ACL2 8.7 executable")
    parser.add_argument("--out", type=Path, required=True, help="A new output directory")
    args = parser.parse_args()
    binary = args.acl2.resolve(strict=True)
    image = (HERE.parents[1] / MODEL).read_bytes()
    out = args.out.absolute()
    out.mkdir()
    model = out / "first-value-numeric"
    proof = out / "proof"
    model.mkdir()
    proof.mkdir()
    write_image_book(model / "ssv-image.lisp", image)
    shutil.copyfile(HERE / "ssv-spec.lisp", model / "ssv-spec.lisp")
    name = "all-vocabulary-profiles"
    shutil.copyfile(HERE / (name + ".lisp"), proof / (name + ".lisp"))
    env = dict(os.environ, ACL2_CUSTOMIZATION="NONE")
    results = {}
    for directory, book in [(model, "ssv-spec"), (model, "ssv-image"), (proof, name)]:
        command = f'(certify-book "{book}" ? nil :ttags nil :defaxioms-okp nil :skip-proofs-okp nil)'
        _, result = run_acl2(binary, env, directory, "certify-" + book, command)
        result["source_sha256"] = sha(directory / (book + ".lisp"))
        result["certificate_sha256"] = sha(directory / (book + ".cert"))
        results[book] = result
    check = f'(include-book "{name}" :uncertified-okp nil :ttags nil)\n:pe {THEOREM}'
    output, results["fresh_readback"] = run_acl2(binary, env, proof, "readback", check)
    statement = f"(DEFTHM {THEOREM} (IMPLIES (AND (NATP TOKEN) (< TOKEN 4019)) (SSV-PROFILE-OK TOKEN (SSV-IMAGE)))"
    if statement not in " ".join(output.upper().split()):
        raise RuntimeError("The fresh ACL2 process did not print the expected theorem.")
    receipt = {"model_sha256": MODEL_SHA, "inclusive_token_ids": [0, 4018], "runs": results}
    (out / "RESULT.json").write_text(json.dumps(receipt, sort_keys=True, indent=2) + "\n")
    print(out / "RESULT.json")


if __name__ == "__main__":
    main()
